CREATE TABLE colaborador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    salario NUMERIC(19, 2) NOT NULL CHECK (salario > 0),
    tipo_colaborador VARCHAR(255) NOT NULL
);

CREATE TABLE colaborador_padrao (
    id BIGINT PRIMARY KEY REFERENCES colaborador (id) ON DELETE CASCADE
);

CREATE TABLE colaborador_comissionado (
    id BIGINT PRIMARY KEY REFERENCES colaborador (id) ON DELETE CASCADE,
    valor_das_vendas NUMERIC(19, 2) NOT NULL CHECK (valor_das_vendas > 0),
    percentual_de_comissao NUMERIC(19, 2) NOT NULL CHECK (percentual_de_comissao > 0),
    comissao NUMERIC(19, 2) NOT NULL
);

CREATE TABLE colaborador_producao (
    id BIGINT PRIMARY KEY REFERENCES colaborador (id) ON DELETE CASCADE,
    quantidade_produzida NUMERIC(19, 2),
    valor_unidade NUMERIC(19, 2)
);
